#!/usr/bin/env python3
"""
Builds the hero + #how glass demonstration assets from ONE clean photo of the room.

  python3 scripts/build-glass-assets.py /path/to/Modern_Living_Room_with_Backyard_Views.png

Outputs
  public/images/privolux-living-room.png   the room photo (full frame, no crop)
  public/images/privolux-glass-mask.png    alpha = visible glass only (inner glazing minus sofa / ottoman)
  public/images/privolux-glass-frost.jpg   frost plate: the glass area diffused with normalised blur
  lib/glazing.ts                           pane polygons in % of the photo (same geometry used for the mask)

All coordinates below are in the SOURCE photo's pixel space (1265 x 1243).

Sofa occluder: traced against measured pixel edges of the photo. The arm top is NOT level: the real edge
sits at y~760 at x=720 and y~757 at x=800, and the dark anti-aliased fringe pixels just above it are frosted too (they belong to the glass, not the sofa).
"""
import sys, pathlib
import numpy as np
from PIL import Image, ImageDraw
from scipy.ndimage import gaussian_filter, binary_dilation

SRC = sys.argv[1] if len(sys.argv) > 1 else "public/images/privolux-living-room.png"
ROOT = pathlib.Path(__file__).resolve().parent.parent
src = Image.open(SRC).convert("RGB")
W, H = src.size
SS = 4                                       # supersampling for anti-aliased mask edges

# Inner glass boundaries (just inside the black frame / mullions). Quads: TL, TR, BR, BL.
# Lower edges of the centre/right panes run behind the sofa, the sofa occluder removes that part.
PANES = {
    "left":   [(66, 14),   (443, 50),  (443, 885), (66, 910)],
    "centre": [(469, 53),  (940, 100), (940, 862), (472, 880)],
    "right":  [(964, 103), (1230, 130), (1232, 740), (967, 740)],
}
# Interior objects that sit IN FRONT of the glass and must never be frosted.
OCCLUDERS = {
    "ottoman": [(0, 857), (60, 855), (150, 860), (164, 872), (164, 935), (0, 935)],
    # Sofa, clockwise from the chaise's bottom-left. The right side overshoots the photo edge on purpose.
    "sofa": [
        (551.5, 1000),                                         # bottom-left of chaise
        (551.5, 880), (555, 866), (562, 858), (580, 853),      # chaise left edge + rounded top-left corner
        (650, 845), (717.1, 838),                              # sloped chaise top edge up to the arm
        # --- armrest: edge positions measured pixel-by-pixel from the photo ---
        (717.1, 768), (717.6, 764), (718.6, 763.3), (719.6, 762.3), (720.6, 761.3),   # arm left edge + rounded corner
        (724, 762),(804.5, 760),
        # --- back cushion ---
        (804.5, 686), (805, 684.8), (807, 684.3), (812, 684.3),  # left edge + rounded top-left corner
        (1270, 684.3),                                         # top edge, past the photo's right edge
        (1270, 1000),
    ],
}

room_output = ROOT / "public/images/privolux-living-room.png"
if pathlib.Path(SRC).resolve() != room_output.resolve():
    src.save(room_output, optimize=True)
a = np.asarray(src).astype(float)

def poly_mask(points):
    m = Image.new("L", (W * SS, H * SS), 0)
    ImageDraw.Draw(m).polygon([(x * SS, y * SS) for x, y in points], fill=255)
    return np.asarray(m.resize((W, H), Image.LANCZOS)).astype(float) / 255

panes = np.clip(sum(poly_mask(p) for p in PANES.values()), 0, 1)
occ = np.zeros((H, W))
for p in OCCLUDERS.values():
    occ = np.maximum(occ, poly_mask(p))
glass = np.clip(panes * (1 - occ), 0, 1)

# ---- mask PNG (alpha only) ----
mask = np.zeros((H, W, 4), np.uint8); mask[..., :3] = 255; mask[..., 3] = (glass * 255).astype(np.uint8)
Image.fromarray(mask, "RGBA").save(ROOT / "public/images/privolux-glass-mask.png", optimize=True)

# ---- frost plate: normalised convolution so frame and furniture never bleed into the glass ----
core = glass > 0.98
core = core & ~binary_dilation(~core, iterations=5)       # only trust pixels well inside the glass
M = core.astype(float)
def nconv(sig):
    num = np.stack([gaussian_filter(a[..., c] * M, sig) for c in range(3)], -1)
    den = gaussian_filter(M, sig)[..., None]
    return num, den
num, den = nconv(50)
num2, den2 = nconv(105)
c = np.where(den > 0.02, num / np.maximum(den, 1e-6), num2 / np.maximum(den2, 1e-6))
c = np.where(den2 > 1e-4, c, 200)
ice = np.array([232, 240, 245], float)
lum_c = c.mean(-1, keepdims=True)
c = lum_c + (c - lum_c) * 0.55                            # desaturate
plate = np.clip((c * 0.34 + ice * 0.66) * 1.02, 0, 255).astype(np.uint8)
Image.fromarray(plate, "RGB").save(ROOT / "public/images/privolux-glass-frost.jpg", quality=88, optimize=True)

# ---- lib/glazing.ts ----
def pct(p):  return [(round(x / W * 100, 3), round(y / H * 100, 3)) for x, y in p]
panes_pct = {k: pct(v) for k, v in PANES.items()}
allx = [x for v in panes_pct.values() for x, _ in v]; ally = [y for v in panes_pct.values() for _, y in v]
L, R, T, B = min(allx), max(allx), min(ally), max(ally)
lines = ["// GENERATED by scripts/build-glass-assets.py. Do not edit by hand; edit the script and re-run it.",
         "// All values are percentages of the photo (privolux-living-room.png), so they hold at any rendered size.", "",
         f"export const GLAZING_IMAGE = {{ width: {W}, height: {H} }} as const;", "",
         "export type PanePoint = readonly [x: number, y: number];",
         "export const PANES: ReadonlyArray<{ id: string; points: ReadonlyArray<PanePoint> }> = ["]
for k, v in panes_pct.items():
    lines.append(f'    {{ id: "{k}", points: [' + ", ".join(f"[{x}, {y}]" for x, y in v) + "] },")
lines += ["];", "",
          "/** Bounding box of all glazing, used for the slider range, scan line and film sweep. */",
          f"export const GLAZING_BOX = {{ left: {L}, right: {R}, top: {T}, bottom: {B}, width: {round(R - L, 3)}, height: {round(B - T, 3)} }} as const;", "",
          "export const polygon = (pts: ReadonlyArray<PanePoint>) => `polygon(${pts.map(([x, y]) => `${x}% ${y}%`).join(\", \")})`;",
          "export const svgPoints = (pts: ReadonlyArray<PanePoint>) => pts.map(([x, y]) => `${x},${y}`).join(\" \");", ""]
(ROOT / "lib/glazing.ts").write_text("\n".join(lines))
print("photo", W, H, "aspect", round(W / H, 4)); print("glazing box", L, R, T, B)

# ---- QA overlay (not shipped): pink = frosted glass, so any sofa leak or gap is obvious ----
qa = a.copy(); tint = np.array([255, 0, 120], float)
qa = qa * (1 - glass[..., None] * 0.55) + tint * glass[..., None] * 0.55
Image.fromarray(qa.astype(np.uint8)).save("/tmp/qa_mask.png")