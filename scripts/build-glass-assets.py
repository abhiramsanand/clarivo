#!/usr/bin/env python3
"""
Builds the #how demonstration assets from the supplied before/after composite.

  python3 scripts/build-glass-assets.py /path/to/Media__1_.jpg

Outputs
  public/images/clarivo-living-room.jpg   clean crop of the CLEAR half (labels, arrow, feature strip removed)
  public/images/clarivo-glass-mask.png    alpha = visible glass (inner glazing minus plant / ottoman / sofa)
  public/images/clarivo-glass-frost.jpg   frost plate: the glass area diffused with normalised blur (no frame/furniture bleed)
  lib/glazing.ts                          pane polygons in % of the crop (same geometry used for the mask)

Coordinates below are in the ORIGINAL composite's pixel space (1536x1024).
"""
import sys, pathlib
import numpy as np
from PIL import Image, ImageDraw
from scipy.ndimage import gaussian_filter, binary_dilation

SRC = sys.argv[1] if len(sys.argv) > 1 else "Media__1_.jpg"
ROOT = pathlib.Path(__file__).resolve().parent.parent
CROP = (0, 144, 718, 852)                  # x0, y0, x1, y1 -> clean left panel, below the BEFORE pills
W, H = CROP[2] - CROP[0], CROP[3] - CROP[1]
SS = 4                                      # supersampling for anti-aliased mask edges

# Inner glass boundaries (inside the black frame / mullions). Perspective-skewed quads: TL, TR, BR, BL.
PANES = {
    "left":   [(37, 154), (256, 176.5), (256, 646.6), (37, 657)],
    "centre": [(266, 178.5), (539, 207), (539, 633), (266, 644.2)],
    "right":  [(547, 208), (698, 223.6), (698, 625.4), (547, 632.3)],
}
# Interior objects that sit IN FRONT of the glass and must never be frosted.
OCCLUDERS = {
    "ottoman": [(36, 636), (60, 634), (88, 639), (91, 646), (88, 657), (36, 660)],
    "sofa": [(310, 645), (313, 630), (340, 624), (380, 620), (409, 618), (409, 577), (430, 576), (482, 578),
             (480, 560), (479, 534), (500, 528), (560, 527), (600, 528), (650, 530), (722, 531), (722, 700), (310, 700)],
}
PLANT_BOX = (0, 425, 118, 572)              # interior plant leaves are segmented by colour inside this box only

src = Image.open(SRC).convert("RGB")
img = src.crop(CROP)
img.save(ROOT / "public/images/clarivo-living-room.jpg", quality=92, optimize=True, progressive=True)
a = np.asarray(img).astype(float)

def poly_mask(points):
    m = Image.new("L", (W * SS, H * SS), 0)
    ImageDraw.Draw(m).polygon([((x - CROP[0]) * SS, (y - CROP[1]) * SS) for x, y in points], fill=255)
    return np.asarray(m.resize((W, H), Image.LANCZOS)).astype(float) / 255

panes = np.clip(sum(poly_mask(p) for p in PANES.values()), 0, 1)
occ = np.zeros((H, W))
for p in OCCLUDERS.values():
    occ = np.maximum(occ, poly_mask(p))

# Interior plant: dark, green-dominant pixels inside PLANT_BOX (exterior tree is light/yellow, fence is blue-grey).
x0, y0, x1, y1 = PLANT_BOX
r, g, b = a[..., 0], a[..., 1], a[..., 2]
lum = (r + g + b) / 3
leaf = (g > r + 4) & (g > b + 14) & (lum < 125)
box = np.zeros((H, W), bool); box[y0 - CROP[1]:y1 - CROP[1], x0:x1] = True
leaf &= box
leaf = binary_dilation(leaf, iterations=2)
leaf = gaussian_filter(leaf.astype(float), 0.8)
occ = np.maximum(occ, leaf)

glass = np.clip(panes * (1 - occ), 0, 1)

# ---- mask PNG (alpha only) ----
mask = np.zeros((H, W, 4), np.uint8); mask[..., :3] = 255; mask[..., 3] = (glass * 255).astype(np.uint8)
Image.fromarray(mask, "RGBA").save(ROOT / "public/images/clarivo-glass-mask.png", optimize=True)

# ---- frost plate: normalised convolution so frame, plant and sofa never bleed into the glass ----
core = glass > 0.98
core = core & ~binary_dilation(~core, iterations=3)       # only trust pixels well inside the glass
M = core.astype(float)
def nconv(sig):
    num = np.stack([gaussian_filter(a[..., c] * M, sig) for c in range(3)], -1)
    den = gaussian_filter(M, sig)[..., None]
    return num, den
num, den = nconv(28)
num2, den2 = nconv(60)
c = np.where(den > 0.02, num / np.maximum(den, 1e-6), num2 / np.maximum(den2, 1e-6))
c = np.where(den2 > 1e-4, c, 200)
# diffuse, milky privacy state: keep a trace of the real exterior colour (sky above, greenery below)
ice = np.array([232, 240, 245], float)
lum_c = c.mean(-1, keepdims=True)
c = lum_c + (c - lum_c) * 0.55                           # desaturate
plate = c * 0.34 + ice * 0.66
plate = np.clip(plate * 1.02, 0, 255).astype(np.uint8)
Image.fromarray(plate, "RGB").save(ROOT / "public/images/clarivo-glass-frost.jpg", quality=88, optimize=True)

# ---- lib/glazing.ts ----
def pct(p):  return [(round((x - CROP[0]) / W * 100, 3), round((y - CROP[1]) / H * 100, 3)) for x, y in p]
panes_pct = {k: pct(v) for k, v in PANES.items()}
allx = [x for v in panes_pct.values() for x, _ in v]; ally = [y for v in panes_pct.values() for _, y in v]
L, R, T, B = min(allx), max(allx), min(ally), max(ally)
lines = ["// GENERATED by scripts/build-glass-assets.py. Do not edit by hand; edit the script and re-run it.",
         "// All values are percentages of the clean crop (clarivo-living-room.jpg), so they hold at any rendered size.", "",
         f"export const GLAZING_IMAGE = {{ width: {W}, height: {H} }} as const;", "",
         "export type PanePoint = readonly [x: number, y: number];",
         "export const PANES: ReadonlyArray<{ id: string; points: ReadonlyArray<PanePoint> }> = ["]
for k, v in panes_pct.items():
    lines.append(f'    {{ id: "{k}", points: [' + ", ".join(f"[{x}, {y}]" for x, y in v) + "] },")
lines += ["];", "",
          "/** Bounding box of all glazing, used for the slider range, scan line and film sweep. */",
          f"export const GLAZING_BOX = {{ left: {L}, right: {R}, top: {T}, bottom: {B}, width: {round(R - L, 3)}, height: {round(B - T, 3)} }} as const;", "",
          "export const polygon = (pts: ReadonlyArray<PanePoint>) => `polygon(${pts.map(([x, y]) => `${x}% ${y}%`).join(\", \")})`;",
          "export const svgPoints = (pts: ReadonlyArray<PanePoint>) => pts.map(([x, y]) => `${x},${y}`).join(\" \");", ""]
(ROOT / "lib/glazing.ts").write_text("\n".join(lines))
print("crop", W, H, "aspect", round(W / H, 4)); print("glazing box", L, R, T, B)

# ---- QA overlay (not shipped) ----
qa = np.asarray(img).astype(float)
tint = np.array([255, 0, 120], float)
qa = qa * (1 - glass[..., None] * 0.55) + tint * glass[..., None] * 0.55
Image.fromarray(qa.astype(np.uint8)).resize((W * 2, H * 2), Image.LANCZOS).save("/home/claude/qa_mask.png")
